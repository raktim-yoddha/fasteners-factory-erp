import { spawn } from 'node:child_process';
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const child = spawn(
  process.execPath,
  [
    fileURLToPath(new URL('../../node_modules/supabase/dist/supabase.js', import.meta.url)),
    'gen',
    'types',
    '--local',
    '--schema',
    'public',
  ],
  { stdio: ['ignore', 'pipe', 'pipe'] },
);
let source = '';
let errors = '';
child.stdout.on('data', (chunk) => {
  source += chunk;
});
child.stderr.on('data', (chunk) => {
  errors += chunk;
});
child.on('error', (error) => {
  console.error(error.message);
  process.exitCode = 1;
});
child.on('close', async (code) => {
  if (code !== 0 || !source.includes('export type Database')) {
    console.error('Database type generation failed. Start the isolated local backend first.');
    console.error(errors.slice(-800));
    process.exitCode = 1;
    return;
  }
  await mkdir('packages/cloud-repository/src/generated', { recursive: true });
  await writeFile(
    'packages/cloud-repository/src/generated/database.ts',
    `// Generated by pnpm db:types. Do not hand-edit.\n${source}`,
  );
  console.log('Generated public database types from the running local schema.');
});
